import { METRICS } from './catalog.js';
import { analyzeMetric, DAY } from './analysis.js';
import { generateScenario, TRUTH, SCENARIO } from '../scenario.js';

/**
 * Replays synthetic crews day by day (no database) and measures:
 *  - DETECTION: days from physiological onset to the first flag, for static thresholds only vs thresholds + drift detection
 *  - FALSE ALARMS: drift alarms per crew-month on crews with NO hidden problem (the detector must stay quiet)
 *
 * IMPORTANT: this is validation on SYNTHETIC data with injected effects — it shows the method behaves as designed,
 * not that it works on real astronauts. Real validation needs flight / analog (HI-SEAS, SIRIUS, Antarctic) data.
 */
const END = Date.UTC(2026, 10, 10, 12);

function replay(scn, metric, days) {
  const pts = scn.measurements.filter(m => m.metric === metric).map(m => ({ t: m.t, v: m.value, v2: m.value2, d: m.d }));
  const rows = [];
  for (let d = 0; d < days; d++) {
    const asOf = END - (days - 1 - d) * DAY + 12 * 36e5;
    const upto = pts.filter(p => p.t <= asOf);
    rows.push({ d, ...analyzeMetric(metric, upto, asOf) });
  }
  return rows;
}

const firstFrom = (rows, from, pred) => rows.find(r => r.d >= from && pred(r))?.d ?? null;

export function runValidation({ crews = 30, nullCrews = 30, days = SCENARIO.days } = {}) {
  const events = TRUTH.map(t => ({ ...t, early: [], threshold: [] }));
  for (let s = 1; s <= crews; s++) {
    const scn = generateScenario({ seed: s, days, endMs: END });
    for (const e of events) {
      const rows = replay(scn, e.metric, days);
      const tDay = firstFrom(rows, e.onset, r => r.thresholdStatus !== 'green' && r.thresholdStatus !== 'none');
      const eDay = firstFrom(rows, e.onset, r => r.status !== 'green' && r.status !== 'none');
      e.threshold.push(tDay == null ? null : tDay - e.onset);
      e.early.push(eDay == null ? null : eDay - e.onset);
    }
  }

  // False alarms: crews with no injected problem. Count drift-only alarm EPISODES (a run of consecutive flagged days = 1).
  const have = new Set(generateScenario({ seed: 1, days, events: false, endMs: END }).measurements.map(m => m.metric));
  const metrics = Object.keys(METRICS).filter(k => METRICS[k].bad && have.has(k));
  let driftEpisodes = 0, thresholdEpisodes = 0;
  const monitoredDays = nullCrews * (days - 14); // first 14 days = baseline window, nothing to compare against
  for (let s = 1; s <= nullCrews; s++) {
    const scn = generateScenario({ seed: 1000 + s, days, events: false, endMs: END });
    for (const k of metrics) {
      const rows = replay(scn, k, days).filter(r => r.d >= 14);
      let inD = false, inT = false;
      for (const r of rows) {
        if (r.early && !inD) driftEpisodes++;
        inD = r.early;
        const t = r.thresholdStatus !== 'green' && r.thresholdStatus !== 'none';
        if (t && !inT) thresholdEpisodes++;
        inT = t;
      }
    }
  }
  const perMonth = n => +(n / (monitoredDays / 30)).toFixed(2);

  const med = a => { const v = a.filter(x => x != null).sort((x, y) => x - y); return v.length ? v[v.length >> 1] : null; };
  const rate = a => +(a.filter(x => x != null).length / a.length).toFixed(2);
  const table = events.map(e => {
    const lead = e.early.map((x, i) => (x != null && e.threshold[i] != null ? e.threshold[i] - x : null)).filter(x => x != null);
    return {
      id: e.id, label: e.label, metric: e.metric, kind: e.kind, onset: e.onset,
      thresholdDetected: rate(e.threshold), earlyDetected: rate(e.early),
      thresholdDelayMedian: med(e.threshold), earlyDelayMedian: med(e.early),
      leadDaysMedian: med(lead),
    };
  });
  return {
    crews, nullCrews, days, table,
    falseAlarms: { driftPerCrewMonth: perMonth(driftEpisodes), thresholdPerCrewMonth: perMonth(thresholdEpisodes), monitoredMetrics: metrics.length },
  };
}

export function toMarkdown(v) {
  const f = x => (x == null ? '—' : x);
  return [
    '# Astra validation report (synthetic data)',
    '',
    `Generated by \`npm run validate\` — ${v.crews} simulated crews with hidden problems, ${v.nullCrews} control crews with none, ${v.days} days each. Deterministic (seeded).`,
    '',
    '> **Read this honestly.** The data is synthetic and the effects were injected by us, so this shows the *method behaves as designed* (earlier, with few false alarms). It does **not** prove accuracy on real astronauts. Next step: replay real flight/analog datasets (e.g. NASA OSDR, HI-SEAS, SIRIUS).',
    '',
    '## Detection — days from onset to first flag',
    '',
    '| Hidden problem | Metric | Onset (day) | Threshold-only: found / median delay | Thresholds + drift: found / median delay | Median days earlier |',
    '|---|---|---|---|---|---|',
    ...v.table.map(t => `| ${t.label} | ${t.metric} | ${t.onset} | ${Math.round(t.thresholdDetected * 100)}% / ${f(t.thresholdDelayMedian)} d | ${Math.round(t.earlyDetected * 100)}% / ${f(t.earlyDelayMedian)} d | ${f(t.leadDaysMedian)} |`),
    '',
    '## False alarms — control crews with no hidden problem',
    '',
    `| Detector | Alarm episodes per crew-month (${v.falseAlarms.monitoredMetrics} metrics monitored) |`,
    '|---|---|',
    `| Static thresholds (normal day-to-day variation trips them) | ${v.falseAlarms.thresholdPerCrewMonth} |`,
    `| Drift early-warning (added by Astra) | ${v.falseAlarms.driftPerCrewMonth} |`,
    '',
    '## Method',
    '',
    '- Baseline = median of the first 14 days (fixed, so slow decline cannot become the new normal).',
    '- Drift = 7-day median at least 3 robust standard errors worse than baseline, at least a metric-specific minimum % change, and a Theil–Sen 14-day trend in the same direction.',
    '- Drift can only raise green → amber. Red remains reserved for threshold breaches and symptoms.',
    '- Thresholds are defaults with stated basis and references (see `server/src/health/references.js`); flight-surgeon limits override them.',
    '',
  ].join('\n');
}
